save_panel <- function(plot_obj, filename, width, height, out_dir = dir_plots, dpi = 600) {
  ggsave(
    filename = file.path(out_dir, paste0(filename, ".pdf")),
    plot = plot_obj,
    width = width,
    height = height,
    device = "pdf"
  )
  
  ggsave(
    filename = file.path(out_dir, paste0(filename, ".png")),
    plot = plot_obj,
    width = width,
    height = height,
    dpi = dpi
  )
  
  ggsave(
    filename = file.path(out_dir, paste0(filename, ".tiff")),
    plot = plot_obj,
    width = width,
    height = height,
    dpi = dpi,
    compression = "lzw"
  )
}

clean_response <- function(x) {
  x_chr <- as.character(x)
  
  dplyr::case_when(
    x_chr %in% c("R", "r", "Responder", "responder", "1", "pCR", "PCR") ~ "R",
    x_chr %in% c("NR", "nr", "Non-responder", "non-responder", "0", "non-pCR") ~ "NR",
    TRUE ~ NA_character_
  )
}

safe_cor <- function(mat, method = "spearman") {
  # mat: patients x genes
  out <- cor(
    mat,
    method = method,
    use = "pairwise.complete.obs"
  )
  diag(out) <- 0
  out[is.na(out)] <- 0
  out
}

cor_to_long <- function(cor_mat, response_label) {
  as_tibble(cor_mat, rownames = "gene_1") %>%
    pivot_longer(
      -gene_1,
      names_to = "gene_2",
      values_to = "rho"
    ) %>%
    filter(gene_1 < gene_2) %>%
    mutate(
      response = response_label,
      abs_rho = abs(rho),
      sign = if_else(rho >= 0, "positive", "negative")
    )
}

compute_connectivity <- function(cor_mat, response_label) {
  diag(cor_mat) <- 0
  
  tibble(
    gene = rownames(cor_mat),
    response = response_label,
    connectivity_abs = rowSums(abs(cor_mat), na.rm = TRUE),
    connectivity_positive = rowSums(ifelse(cor_mat > 0, cor_mat, 0), na.rm = TRUE),
    connectivity_negative_abs = rowSums(ifelse(cor_mat < 0, abs(cor_mat), 0), na.rm = TRUE)
  )
}

get_hclust_gene_order <- function(cor_mat) {
  dist_mat <- as.dist(1 - cor_mat)
  hc <- hclust(dist_mat, method = "average")
  rownames(cor_mat)[hc$order]
}

make_correlation_heatmap <- function(cor_mat, gene_order, title_text, show_gene_labels = TRUE) {
  plot_tbl <- as_tibble(
    cor_mat[gene_order, gene_order, drop = FALSE],
    rownames = "gene_1"
  ) %>%
    pivot_longer(
      -gene_1,
      names_to = "gene_2",
      values_to = "rho"
    ) %>%
    mutate(
      gene_1 = factor(gene_1, levels = rev(gene_order)),
      gene_2 = factor(gene_2, levels = gene_order)
    )
  
  ggplot(plot_tbl, aes(x = gene_2, y = gene_1, fill = rho)) +
    geom_tile(color = NA) +
    scale_fill_gradient2(
      low = heatmap_div_low,
      mid = heatmap_div_mid,
      high = heatmap_div_high,
      midpoint = 0,
      limits = c(-1, 1)
    ) +
    coord_fixed() +
    theme(
      panel.grid = element_blank(),
      axis.text.x = element_text(
        angle = 90,
        hjust = 1,
        vjust = 0.5,
        size = ifelse(show_gene_labels, 5, 1.5)
      ),
      axis.text.y = element_text(
        size = ifelse(show_gene_labels, 5, 1.5)
      )
    ) +
    labs(
      title = title_text,
      x = NULL,
      y = NULL,
      fill = "Spearman\nrho"
    )
}

make_network_plot <- function(edge_tbl, node_tbl, title_text) {
  
  edge_use <- edge_tbl %>%
    filter(abs_rho >= network_min_abs_rho) %>%
    arrange(desc(abs_rho)) %>%
    slice_head(n = network_top_edges)
  
  if (nrow(edge_use) < 10) {
    edge_use <- edge_tbl %>%
      arrange(desc(abs_rho)) %>%
      slice_head(n = network_top_edges)
  }
  
  graph_obj <- igraph::graph_from_data_frame(
    d = edge_use %>%
      select(from = gene_1, to = gene_2, rho, abs_rho, sign),
    vertices = node_tbl,
    directed = FALSE
  )
  
  layout_mat <- igraph::layout_with_fr(graph_obj)
  
  node_layout <- tibble(
    gene = igraph::V(graph_obj)$name,
    x = layout_mat[, 1],
    y = layout_mat[, 2]
  ) %>%
    left_join(node_tbl, by = "gene")
  
  edge_layout <- igraph::as_data_frame(graph_obj, what = "edges") %>%
    as_tibble() %>%
    left_join(
      node_layout %>% select(from = gene, x_from = x, y_from = y),
      by = "from"
    ) %>%
    left_join(
      node_layout %>% select(to = gene, x_to = x, y_to = y),
      by = "to"
    )
  
  ggplot() +
    geom_segment(
      data = edge_layout,
      aes(
        x = x_from,
        y = y_from,
        xend = x_to,
        yend = y_to,
        color = sign,
        linewidth = abs_rho
      ),
      alpha = 0.55
    ) +
    geom_point(
      data = node_layout,
      aes(
        x = x,
        y = y,
        size = connectivity_abs,
        fill = dominant_cluster
      ),
      shape = 21,
      color = "grey20",
      alpha = 0.95
    ) +
    geom_text(
      data = node_layout,
      aes(x = x, y = y, label = gene),
      size = 2.3,
      vjust = -0.7,
      check_overlap = TRUE
    ) +
    scale_color_manual(values = pal_edge_sign, drop = FALSE) +
    scale_fill_manual(values = pal_cluster_identity_master, na.value = "grey70", drop = FALSE) +
    scale_linewidth_continuous(range = c(0.2, 1.2)) +
    scale_size_continuous(range = c(2, 7)) +
    theme_void(base_size = 11) +
    theme(
      legend.position = "right"
    ) +
    labs(
      title = title_text,
      color = "Correlation\nsign",
      linewidth = "|rho|",
      size = "Connectivity",
      fill = "Dominant RF240\ncluster"
    )
}


