cat("\n[4] Building exploratory DE gene lists and Hallmark enrichment...\n")

exploratory_de_lists_tbl <- de_all_tbl %>%
  mutate(
    direction = case_when(
      PValue < de_nominal_p_cutoff &
        logFC_R_vs_NR > de_abs_logfc_cutoff ~ "R_up",
      PValue < de_nominal_p_cutoff &
        logFC_R_vs_NR < -de_abs_logfc_cutoff ~ "NR_up",
      TRUE ~ NA_character_
    )
  ) %>%
  filter(!is.na(direction)) %>%
  group_by(cluster_identity, direction) %>%
  summarise(
    genes = list(unique(gene)),
    n_genes = n(),
    .groups = "drop"
  )

