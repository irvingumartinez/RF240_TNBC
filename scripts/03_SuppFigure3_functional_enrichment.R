clean_response <- function(x) {
  x_chr <- as.character(x)
  
  dplyr::case_when(
    x_chr %in% c("R", "r", "Responder", "responder", "1", "pCR", "PCR") ~ "R",
    x_chr %in% c("NR", "nr", "Non-responder", "non-responder", "0", "non-pCR") ~ "NR",
    TRUE ~ NA_character_
  )
}

clean_term_label <- function(x) {
  x %>%
    stringr::str_replace("^HALLMARK_", "") %>%
    stringr::str_replace("^GOBP_", "") %>%
    stringr::str_replace("^GO_", "") %>%
    stringr::str_replace_all("_", " ") %>%
    stringr::str_to_sentence()
}

safe_neglog10 <- function(x) {
  x <- ifelse(is.na(x), NA_real_, x)
  x <- ifelse(x <= 0, .Machine$double.xmin, x)
  -log10(x)
}

