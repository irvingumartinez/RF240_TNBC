get_msigdb_t2g <- function(collection, subcollection = NULL) {
  out <- tryCatch({
    if (is.null(subcollection)) {
      msigdbr(species = "Homo sapiens", collection = collection)
    } else {
      msigdbr(
        species = "Homo sapiens",
        collection = collection,
        subcollection = subcollection
      )
    }
  }, error = function(e1) {
    tryCatch({
      if (is.null(subcollection)) {
        msigdbr(species = "Homo sapiens", category = collection)
      } else {
        msigdbr(
          species = "Homo sapiens",
          category = collection,
          subcategory = subcollection
        )
      }
    }, error = function(e2) {
      stop(
        "Could not retrieve MSigDB gene sets with msigdbr. ",
        "Check msigdbr version/API. Original error: ", e1$message
      )
    })
  })
  
  out %>%
    dplyr::select(gs_name, gene_symbol) %>%
    distinct() %>%
    filter(!is.na(gs_name), !is.na(gene_symbol))
}

run_enricher_safe <- function(genes, term2gene, universe, label) {
  genes <- unique(genes)
  genes <- genes[!is.na(genes) & genes != ""]
  genes <- intersect(genes, universe)
  
  if (length(genes) < min_genes_for_enrichment) {
    return(tibble(
      analysis_label = label,
      n_input_genes = length(genes),
      ID = NA_character_,
      Description = NA_character_,
      GeneRatio = NA_character_,
      BgRatio = NA_character_,
      pvalue = NA_real_,
      p.adjust = NA_real_,
      qvalue = NA_real_,
      geneID = NA_character_,
      Count = NA_integer_
    ))
  }
  
  enrich_obj <- tryCatch(
    clusterProfiler::enricher(
      gene = genes,
      universe = universe,
      TERM2GENE = term2gene,
      pvalueCutoff = 1,
      qvalueCutoff = 1,
      minGSSize = 10,
      maxGSSize = 500
    ),
    error = function(e) NULL
  )
  
  if (is.null(enrich_obj)) {
    return(tibble(
      analysis_label = label,
      n_input_genes = length(genes),
      ID = NA_character_,
      Description = NA_character_,
      GeneRatio = NA_character_,
      BgRatio = NA_character_,
      pvalue = NA_real_,
      p.adjust = NA_real_,
      qvalue = NA_real_,
      geneID = NA_character_,
      Count = NA_integer_
    ))
  }
  
  res <- as_tibble(enrich_obj@result)
  
  if (nrow(res) == 0) {
    return(tibble(
      analysis_label = label,
      n_input_genes = length(genes),
      ID = NA_character_,
      Description = NA_character_,
      GeneRatio = NA_character_,
      BgRatio = NA_character_,
      pvalue = NA_real_,
      p.adjust = NA_real_,
      qvalue = NA_real_,
      geneID = NA_character_,
      Count = NA_integer_
    ))
  }
  
  res %>%
    mutate(
      analysis_label = label,
      n_input_genes = length(genes)
    ) %>%
    relocate(analysis_label, n_input_genes)
}


