# Important:
# We avoid matrix multiplication across all cells because it can exhaust memory.
# Instead, we aggregate counts per patient-response sample using rowSums group by group.

counts_assay <- assay(sce, "counts")

cat("\nCounts assay class:\n")
print(class(counts_assay))

run_cluster_pseudobulk_de <- function(cluster_name) {
  
  cat("\n  - Cluster: ", cluster_name, "\n")
  
  # Cells belonging to the selected reanalyzed cluster
  meta_sub <- meta %>%
    filter(
      cluster_identity == cluster_name,
      !is.na(patient_id),
      !is.na(response)
    )
  
  if (nrow(meta_sub) == 0) {
    warning("No cells found for cluster: ", cluster_name)
    return(NULL)
  }
  
  # Ensure cell order is valid
  meta_sub <- meta_sub %>%
    mutate(
      cell_index = match(cell_id, colnames(sce))
    ) %>%
    filter(!is.na(cell_index))
  
  if (nrow(meta_sub) == 0) {
    warning("No valid matched cells for cluster: ", cluster_name)
    return(NULL)
  }
  
  # Define patient-level pseudobulk samples
  meta_sub <- meta_sub %>%
    mutate(
      sample_group = paste(patient_id, response, sep = "__")
    )
  
  sample_meta <- meta_sub %>%
    count(sample_group, patient_id, response, name = "n_cells") %>%
    mutate(
      response = factor(response, levels = c("NR", "R"))
    ) %>%
    filter(n_cells >= min_cells_per_patient_cluster)
  
  if (nrow(sample_meta) < 4 || length(unique(sample_meta$response)) < 2) {
    warning(
      "Not enough patient-level pseudobulk samples after filtering for cluster: ",
      cluster_name
    )
    return(NULL)
  }
  
  cat("    Cells before sample filtering: ", nrow(meta_sub), "\n")
  cat("    Pseudobulk samples retained: ", nrow(sample_meta), "\n")
  cat("    R samples: ", sum(sample_meta$response == "R"), "\n")
  cat("    NR samples: ", sum(sample_meta$response == "NR"), "\n")
  
  # Memory-safe pseudobulk aggregation:
  # For each retained patient-response sample, sum counts across its cells.
  pb_list <- lapply(sample_meta$sample_group, function(sg) {
    
    idx <- meta_sub %>%
      filter(sample_group == sg) %>%
      pull(cell_index)
    
    Matrix::rowSums(counts_assay[, idx, drop = FALSE])
  })
  
  pb_counts <- do.call(cbind, pb_list)
  colnames(pb_counts) <- sample_meta$sample_group
  rownames(pb_counts) <- rownames(sce)
  
  # Remove genes with zero counts across all pseudobulk samples before edgeR
  keep_nonzero <- Matrix::rowSums(pb_counts) > 0
  pb_counts <- pb_counts[keep_nonzero, , drop = FALSE]
  
  # Convert only the small pseudobulk matrix to base matrix.
  # This is much smaller than the cell-level matrix.
  pb_counts_mat <- as.matrix(pb_counts)
  
  dge <- edgeR::DGEList(
    counts = pb_counts_mat,
    samples = as.data.frame(sample_meta)
  )
  
  keep_genes <- edgeR::filterByExpr(
    dge,
    group = sample_meta$response
  )
  
  dge <- dge[keep_genes, , keep.lib.sizes = FALSE]
  dge <- edgeR::calcNormFactors(dge)
  
  design <- model.matrix(~ 0 + response, data = sample_meta)
  colnames(design) <- gsub("^response", "", colnames(design))
  
  if (!all(c("R", "NR") %in% colnames(design))) {
    warning(
      "Design matrix does not contain both R and NR columns for cluster: ",
      cluster_name
    )
    return(NULL)
  }
  
  dge <- edgeR::estimateDisp(dge, design)
  fit <- edgeR::glmQLFit(dge, design)
  
  contrast <- makeContrasts(R - NR, levels = design)
  qlf <- edgeR::glmQLFTest(fit, contrast = contrast)
  
  de_tbl <- edgeR::topTags(qlf, n = Inf)$table %>%
    as_tibble(rownames = "gene") %>%
    rename(
      logFC_R_vs_NR = logFC,
      logCPM = logCPM,
      F = F,
      PValue = PValue,
      FDR = FDR
    ) %>%
    mutate(
      cluster_identity = cluster_name,
      n_cells_cluster = nrow(meta_sub),
      n_pb_samples = nrow(sample_meta),
      n_R_samples = sum(sample_meta$response == "R"),
      n_NR_samples = sum(sample_meta$response == "NR")
    ) %>%
    relocate(cluster_identity)
  
  pb_meta_tbl <- sample_meta %>%
    mutate(cluster_identity = cluster_name) %>%
    relocate(cluster_identity)
  
  # Clean intermediate objects before moving to next cluster
  rm(pb_list, pb_counts, pb_counts_mat, dge, fit, qlf)
  gc()
  
  list(
    de = de_tbl,
    pb_meta = pb_meta_tbl
  )
}

