make_rf240_enrichment_plot <- function(enrich_tbl, top_n, title_text, subtitle_text) {
  plot_tbl <- enrich_tbl %>%
    filter(!is.na(ID)) %>%
    group_by(module) %>%
    arrange(p.adjust, pvalue, .by_group = TRUE) %>%
    slice_head(n = top_n) %>%
    ungroup() %>%
    mutate(
      module = factor(module, levels = unique(rf240_module_lists_tbl$module)),
      term_clean = factor(term_clean, levels = rev(unique(term_clean)))
    )
  
  if (nrow(plot_tbl) == 0) {
    return(empty_plot(title_text))
  }
  
  ggplot(
    plot_tbl,
    aes(
      x = module,
      y = term_clean,
      size = Count,
      color = neg_log10_padj
    )
  ) +
    geom_point(alpha = 0.9) +
    scale_color_gradient(
      low = "grey80",
      high = "#08519C",
      na.value = "grey90"
    ) +
    scale_size_continuous(range = c(1.2, 5)) +
    theme(
      axis.text.x = element_text(angle = 45, hjust = 1),
      panel.grid.minor = element_blank()
    ) +
    labs(
      title = title_text,
      subtitle = subtitle_text,
      x = "RF240 gene set/module",
      y = NULL,
      color = "-log10 FDR",
      size = "Gene count"
    )
}

